import { expect, test } from "@playwright/test";
import { checkWorkspace, stat } from "./shared-ui";

test("authenticated records drive the shared dashboard, planner and analytics across mode switches", async ({page}, info) => {
  test.setTimeout(150000);
  if (process.env.SMART_FLOW_TEST_URL !== "http://127.0.0.1:57421" || !process.env.SMART_FLOW_TEST_ANON_KEY)
    throw new Error("Run with the disposable smart-flow-verify stack.");
  const exceptions: string[] = [];
  page.on("pageerror", e => exceptions.push(e.message));
  const screenshot = async (name: string) => {
    const path = process.env.CAPTURE_README_IMAGES === "1" ? `docs/images/${name}.png` : info.outputPath(name + ".png");
    await page.screenshot({ path, animations:"disabled" });
    await info.attach(name, { path, contentType:"image/png" });
  };
  const demoStore = () => page.evaluate(() => localStorage.getItem("smart-taskflow-demo-store"));
  const overview = page.getByRole("tab", {name:/Overview|Home/});
  const tasks = page.getByRole("tab", {name:/Task Manager|^Tasks$/});
  const planner = page.getByRole("tab", {name:/Daily Planner|^Planner$/});
  const analytics = page.getByRole("tab", {name:/Analytics|Stats/});
  const signOut = page.getByRole("button", {name:"Sign out"});
  const explore = page.getByRole("button", {name:"Explore Demo"});
  await page.goto("/");
  await explore.click();
  await expect(stat(page, "Open tasks")).toHaveText("28");
  const savedDemo = await demoStore();
  await signOut.click();

  const email = `parity-${crypto.randomUUID()}@example.test`;
  const password = crypto.randomUUID();
  await page.getByRole("button", {name:"Register", exact:true}).click();
  await page.getByLabel("Display name").fill("Design studio");
  await page.getByLabel("Email", {exact:true}).fill(email);
  await page.getByLabel("Password", {exact:true}).fill(password);
  await page.getByRole("button", {name:"Create account"}).click();
  await expect(page.getByText("Cloud · Supabase")).toBeVisible();
  await expect(stat(page, "Open tasks")).toHaveText("0");
  await expect(stat(page, "Completion rate")).toHaveText("—");
  await expect(page.getByRole("button", {name:/Reset demo|Export saved data/})).toHaveCount(0);
  await screenshot("cloud-empty");
  await page.getByRole("button", {name:"Plan your first work session"}).click();
  await expect(page.getByLabel("Planned start")).toHaveValue(/T09:00$/);
  await page.getByRole("dialog").press("Escape");
  await analytics.click();
  await expect(stat(page, "Total tasks")).toHaveText("0");
  await expect(page.getByText(/No completions this week/)).toBeVisible();
  await expect(page.getByText("No completed tasks yet.")).toBeVisible();
  await overview.click();
  const planned = "Review the research brief";
  const completed = "Share the interview summary";
  await page.getByRole("button", {name:"Create your first task"}).click();
  await page.getByLabel("Title", {exact:true}).fill(planned);
  await page.getByRole("button", {name:"Create Task", exact:true}).click();
  await expect(stat(page, "Open tasks")).toHaveText("1");
  await planner.click();
  const day = await page.getByLabel("Planner date").inputValue();
  await page.getByRole("button", {name:"Schedule " + planned, exact:true}).press("Enter");
  await page.getByLabel("Planned start").fill(day + "T14:00");
  await page.getByRole("button", {name:"Save placement"}).click();
  await expect(page.getByRole("button", {name:"Reschedule " + planned})).toBeVisible();
  await tasks.click();
  await page.getByRole("button", {name:"Add Task"}).click();
  await page.getByLabel("Title", {exact:true}).fill(completed);
  await page.getByRole("button", {name:"Create Task", exact:true}).click();
  await page.getByRole("button", {name:"Complete " + completed, exact:true}).click();
  await expect(page.getByText("Task completed", {exact:true})).toBeVisible();
  await page.reload();
  await expect(stat(page, "Open tasks")).toHaveText("1");
  await expect(stat(page, "Completed today")).toHaveText("1");
  await expect(stat(page, "Completion rate")).toHaveText("50.0%");
  await expect(page.getByText(planned, {exact:true})).toBeVisible();
  await screenshot("cloud-overview");
  await analytics.click();
  await expect(stat(page, "Completed")).toHaveText("1");
  await expect(page.getByRole("list", {name:"Completion timeline"}).getByText(completed)).toBeVisible();
  await screenshot("cloud-analytics");
  await checkWorkspace(page, info);
  await page.route("**/rest/v1/tasks?*", route => route.fulfill({status:503, json:{message:"Workspace temporarily unavailable"}}));
  await page.reload();
  await expect(page.getByRole("status").filter({hasText:"Loading workspace"})).toBeVisible();
  // Allow the PostgREST client's retries for a transient 503 to finish.
  await expect(page.getByRole("alert")).toContainText("Workspace temporarily unavailable", {timeout: 30000});
  await expect(page.getByRole("button", {name:/Reset demo|Export saved data/})).toHaveCount(0);
  await page.unroute("**/rest/v1/tasks?*");
  await page.getByRole("button", {name:"Retry", exact:true}).click();
  await expect(stat(page, "Open tasks")).toHaveText("1");
  expect(await demoStore()).toBe(savedDemo);
  await signOut.click();
  await explore.click();
  await expect(stat(page, "Open tasks")).toHaveText("28");
  await tasks.click();
  await expect(page.getByRole("button", {name:/^Edit /})).toHaveCount(48);
  await expect(page.getByText(planned, {exact:true})).toHaveCount(0);
  await expect(page.getByText(completed, {exact:true})).toHaveCount(0);
  await signOut.click();
  await page.getByLabel("Email", {exact:true}).fill(email);
  await page.getByLabel("Password", {exact:true}).fill(password);
  await page.getByRole("button", {name:"Sign in to cloud"}).click();
  await tasks.click();
  await expect(page.getByRole("button", {name:/^Edit /})).toHaveCount(2);
  await expect(page.getByRole("button", {name:"Edit " + planned})).toBeVisible();
  await expect(page.getByRole("button", {name:"Edit " + completed})).toBeVisible();
  expect(exceptions).toEqual([]);
});
